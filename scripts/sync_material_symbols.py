#!/usr/bin/env python3
"""Import nia's pinned Material Symbols subset, or verify it locally without network access.

Run --download after deliberately editing material_symbols.json. The normal --check mode
verifies the bundled resources and generated catalog. Gradle never downloads icon assets.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
from pathlib import Path
import re
import tempfile
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "scripts/material_symbols.json"
MODEL = ROOT / "app/src/main/java/dev/robinsiegl/nia/model/ShortcutIcon.kt"
DRAWABLES = ROOT / "app/src/main/res/drawable"
RESOURCES = ROOT / "app/src/main/java/dev/robinsiegl/nia/ui/ShortcutIconResources.kt"
LICENSE = ROOT / "app/src/main/assets/licenses/material-symbols-Apache-2.0.txt"
ANDROID = "{http://schemas.android.com/apk/res/android}"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def validate(manifest: dict) -> None:
    assert re.fullmatch(r"[0-9a-f]{40}", manifest["revision"]), "Pin an upstream commit"
    assert manifest["style"] == "materialsymbolsoutlined"
    assert manifest["weight"] == 300 and manifest["opticalSize"] == 24
    icons = manifest["icons"]
    assert len({i["id"] for i in icons}) == len(icons), "Duplicate icon ID"
    assert len({i["symbol"] for i in icons}) == len(icons), "Duplicate symbol"
    for icon in icons:
        assert re.fullmatch(r"[A-Z][A-Z0-9_]*", icon["id"])
        assert re.fullmatch(r"[a-z][a-z0-9_]*", icon["symbol"])
        assert icon["label"].strip() == icon["label"] and icon["label"]
        assert icon["category"] in manifest["categories"]
    assert not {"SETTINGS", "EMPTY", "APPS"} & {i["id"] for i in icons}, "Keep reserved actions separate"


def generated_model(manifest: dict) -> str:
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    groups = ", ".join(f"{key}({quote(label)})" for key, label in manifest["categories"].items())
    entries = ",\n".join(f'    {i["id"]}({quote(i["label"])}, IconCategory.{i["category"]}, {quote(i["keywords"])})' for i in manifest["icons"])
    return f'''// Generated by scripts/sync_material_symbols.py; edit scripts/material_symbols.json instead.
package dev.robinsiegl.nia.model

import kotlinx.serialization.Serializable

enum class IconCategory(val label: String) {{ {groups} }}

/** Stable names are persisted in settings and backups. Never rename or reuse an existing ID. */
@Serializable
enum class ShortcutIcon(val label: String, val category: IconCategory, val keywords: String) {{
{entries}
}}
'''


def generated_resources(manifest: dict) -> str:
    cases = "\n".join(f'    ShortcutIcon.{i["id"]} -> R.drawable.ic_material_{i["symbol"]}' for i in manifest["icons"])
    return f'''// Generated by scripts/sync_material_symbols.py; paths are Google's Material Symbols under Apache-2.0.
package dev.robinsiegl.nia.ui

import androidx.annotation.DrawableRes
import dev.robinsiegl.nia.R
import dev.robinsiegl.nia.model.ShortcutIcon

@get:DrawableRes
internal val ShortcutIcon.drawable: Int get() = when (this) {{
{cases}
}}
'''


def source_path(symbol: str) -> str:
    return f"symbols/android/{symbol}/materialsymbolsoutlined/{symbol}_wght300_24px.xml"


def imported_vector(raw: bytes, symbol: str, revision: str) -> bytes:
    text = raw.decode("utf-8")
    root = ET.fromstring(text)
    assert root.tag == "vector" and root.get(ANDROID + "width") == "24dp"
    assert root.findall("path"), f"No vector paths for {symbol}"
    # Keep Google's paths unchanged; tint belongs to nia's shared foreground palette.
    text = re.sub(r'\s+android:tint="[^"]+"', "", text)
    notice = f'''<!--
  Material Symbols by Google, Apache License 2.0. See assets/licenses/material-symbols-Apache-2.0.txt.
  Source: google/material-design-icons@{revision}/{source_path(symbol)}
  Modified for nia: removed Android theme tint; the shared foreground color is applied in Compose.
-->
'''
    return (notice + text).encode("utf-8")


def check(manifest: dict) -> None:
    validate(manifest)
    assert MODEL.read_text() == generated_model(manifest), "Regenerate ShortcutIcon.kt"
    assert RESOURCES.read_text() == generated_resources(manifest), "Regenerate ShortcutIconResources.kt"
    assert digest(LICENSE.read_bytes()) == manifest["licenseSha256"], "License changed"
    symbols = {i["symbol"] for i in manifest["icons"]} | set(manifest["interfaceSymbols"])
    expected = {f"ic_material_{s}.xml" for s in symbols}
    assert {p.name for p in DRAWABLES.glob("ic_material_*.xml")} == expected, "Unexpected or missing resources"
    for symbol in symbols:
        data = (DRAWABLES / f"ic_material_{symbol}.xml").read_bytes()
        assert digest(data) == manifest["resourceSha256"][symbol], f"Asset changed: {symbol}"
        root = ET.fromstring(data)
        assert root.get(ANDROID + "tint") is None and root.findall("path")
    print(f"Verified {len(manifest['icons'])} selectable Material Symbols, {len(symbols)} vectors and Apache-2.0 license.")


def download(manifest: dict) -> None:
    validate(manifest)
    revision = manifest["revision"]
    base = f"https://raw.githubusercontent.com/google/material-design-icons/{revision}/"
    symbols = sorted({i["symbol"] for i in manifest["icons"]} | set(manifest["interfaceSymbols"]))
    cache = Path(tempfile.gettempdir()) / "nia-material-symbols" / revision
    cache.mkdir(parents=True, exist_ok=True)
    def fetch(symbol: str) -> tuple[str, bytes]:
        cached = cache / f"{symbol}.xml"
        if cached.exists():
            raw = cached.read_bytes()
        else:
            with urllib.request.urlopen(base + source_path(symbol), timeout=45) as response:
                raw = response.read()
            cached.write_bytes(raw)
        return symbol, imported_vector(raw, symbol, revision)
    assets = {}
    failures = []
    with ThreadPoolExecutor(max_workers=12) as pool:
        jobs = {pool.submit(fetch, symbol): symbol for symbol in symbols}
        for future in as_completed(jobs):
            try:
                symbol, data = future.result()
                assets[symbol] = data
            except Exception as exc:
                failures.append(f"{jobs[future]}: {exc}")
    if failures:
        raise RuntimeError("Could not import: " + "; ".join(sorted(failures)))
    with urllib.request.urlopen(base + "LICENSE", timeout=45) as response:
        license_bytes = response.read()
    assert b"Apache License" in license_bytes and b"Version 2.0" in license_bytes
    # Do not leave half an imported catalog if an upstream file is missing.
    for symbol, data in assets.items():
        (DRAWABLES / f"ic_material_{symbol}.xml").write_bytes(data)
    LICENSE.write_bytes(license_bytes)
    MODEL.write_text(generated_model(manifest))
    RESOURCES.write_text(generated_resources(manifest))
    manifest["licenseSha256"] = digest(license_bytes)
    manifest["resourceSha256"] = {symbol: digest(assets[symbol]) for symbol in symbols}
    MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    check(manifest)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="Verify local assets; no network")
    modes.add_argument("--download", action="store_true", help="Import the pinned upstream subset")
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    (download if args.download else check)(manifest)


if __name__ == "__main__":
    main()
